#!/usr/bin/env python3
"""
build_adversarial_lean.py
=========================
Regenerate Lean Taxpayer instances for every adversarial JSON case and
rewrite AdversarialProbe.lean with positive + negated theorems.

Also writes a predicate-mirror Lean-results JSONL (for hosts without lake),
evaluating the same Boolean logic as AdversarialRules.lean against each
JSON instance. Marked source=predicate_mirror — re-prove with
verify_one_lake.py --adversarial when lake is available.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GT_PATH = ROOT / "data/tax/adversarial/ground_truth.jsonl"
LEAN_DIR = ROOT / "Reglib_tax/Reglib/ITA"
PROBE_PATH = LEAN_DIR / "AdversarialProbe.lean"
MIRROR_OUT = ROOT / "reports/adversarial_lean_results.jsonl"
PY = sys.executable


def load_gt() -> list[dict]:
    return [
        json.loads(l)
        for l in GT_PATH.read_text(encoding="utf-8").splitlines()
        if l.strip()
    ]


def regenerate_instances(cases: list[dict]) -> None:
    for case in cases:
        cid = case["id"]
        inp = ROOT / case["taxpayer_file"]
        out = LEAN_DIR / f"Adversarial_{cid}.lean"
        cmd = [
            PY, str(ROOT / "scripts/generate_taxpayer_lean.py"),
            "--input", str(inp),
            "--instance-name", cid,
            "--out", str(out),
        ]
        subprocess.run(cmd, check=True, cwd=str(ROOT))


def write_probe(cases: list[dict]) -> None:
    lines = [
        "-- Reglib_tax/Reglib/ITA/AdversarialProbe.lean",
        "-- Auto-generated by build_adversarial_lean.py — DO NOT EDIT MANUALLY",
        "-- Each case: positive + negated theorem; exactly one should close.",
        "",
        "import Reglib.ITA.AdversarialRules",
    ]
    for case in cases:
        lines.append(f"import Reglib.ITA.Adversarial_{case['id']}")
    lines += [
        "",
        "namespace Reglib.ITA.Rules",
        "",
        "open Reglib.ITA",
        "",
        "/-! ## Adversarial theorems — LLM judge reliability at rule boundaries -/",
        "",
    ]
    for case in cases:
        cid = case["id"]
        pred = case["lean_predicate"]
        gt = case["ground_truth_verdict"]
        lines.append(f"/-! ### {cid} (GT = {gt}) -/")
        lines.append("")
        lines.append(f"/-- Positive: {pred}. -/")
        lines.append(f"theorem gold_{cid} : {pred} {cid} := by")
        lines.append("  sorry")
        lines.append("")
        lines.append(f"/-- Negated: ¬{pred}. -/")
        lines.append(f"theorem gold_{cid}_negated : {pred}_negated {cid} := by")
        lines.append("  sorry")
        lines.append("")
    lines.append("end Reglib.ITA.Rules")
    lines.append("")
    PROBE_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"[build] Wrote {PROBE_PATH} ({len(cases)} cases × 2 theorems)")


def eval_pred(name: str, t: dict) -> bool:
    """Mirror of AdversarialRules.lean (FY 2024–25)."""
    if name == "adv_112a_taxable":
        return t["ltcg_listed_equity_amount"] > t["ltcg_exempt_limit"]
    if name == "adv_87a_rebate_eligible":
        return (not t["is_new_tax_regime"]) and (
            t["total_income_amount"] <= t["rebate_87a_threshold"]
        )
    if name == "adv_111a_concessional":
        return t["is_stt_paid_on_transfer"] and t["stcg_listed_equity_amount"] > 0
    if name == "adv_80d_full_deduction":
        if t["is_senior_citizen"]:
            return t["health_insurance_premium_amount"] <= t["max_80d_deduction_senior"]
        return t["health_insurance_premium_amount"] <= t["max_80d_deduction_self"]
    if name == "adv_6_1_resident":
        return t["days_in_india_fy"] >= 182
    if name == "adv_194_tds_applies":
        return t["dividend_income_amount"] > t["dividend_tds_threshold"]
    if name == "adv_194a_tds_applies":
        if t["is_senior_citizen"]:
            return t["interest_income_bank_amount"] > t["interest_threshold_senior_bank"]
        return t["interest_income_bank_amount"] > t["interest_threshold_bank"]
    if name == "adv_139_1_filing_required":
        return t["total_income_amount"] > t["basic_exemption_limit"]
    if name == "adv_80c_full_investment_deductible":
        return (not t["is_new_tax_regime"]) and (
            t["investment_80c_amount"] <= t["max_80c_deduction"]
        )
    if name == "adv_234b_interest_applies":
        return (
            t["advance_tax_paid_amount"] * 100
            < t["assessed_tax_amount"] * t["advance_tax_threshold_pct"]
        )
    if name == "adv_111a_short_term_at_12m":
        return (
            t["holding_period_months_equity"] <= 12
            and t["is_stt_paid_on_transfer"]
            and t["stcg_listed_equity_amount"] > 0
        )
    if name == "adv_80c_deduction_allowed":
        return (not t["is_new_tax_regime"]) and t["investment_80c_amount"] > 0
    if name == "adv_87a_new_regime_eligible":
        return t["is_new_tax_regime"] and (
            t["total_income_amount"] <= t["rebate_87a_new_threshold"]
        )
    if name == "adv_194_rate_20pct":
        return not t["is_pan_furnished"]
    if name == "adv_194a_rate_20pct":
        return not t["is_pan_furnished"]
    raise KeyError(f"Unknown predicate: {name}")


def write_mirror_results(cases: list[dict]) -> None:
    rows = []
    mismatches = []
    for case in cases:
        t = json.loads(Path(ROOT / case["taxpayer_file"]).read_text(encoding="utf-8"))
        pred = case["lean_predicate"]
        holds = eval_pred(pred, t)
        gt = case["ground_truth_verdict"]
        if holds != gt:
            mismatches.append((case["id"], holds, gt))
        # Symmetric collapse: positive proved iff holds; negated iff not holds
        rows.append({
            "id": case["id"],
            "verdict": holds,
            "positive_proved": holds,
            "negated_proved": not holds,
            "source": "predicate_mirror",
            "lean_predicate": pred,
            "note": "Mirror of AdversarialRules.lean; re-prove with lake when available",
        })
    MIRROR_OUT.parent.mkdir(parents=True, exist_ok=True)
    MIRROR_OUT.write_text(
        "\n".join(json.dumps(r) for r in rows) + "\n",
        encoding="utf-8",
    )
    print(f"[build] Wrote {MIRROR_OUT} ({len(rows)} cases, source=predicate_mirror)")
    if mismatches:
        print("[build] ERROR: predicate mirror ≠ ground truth:")
        for m in mismatches:
            print(f"  {m}")
        raise SystemExit(1)
    print("[build] All mirror verdicts match ground truth (by construction check OK)")


def main() -> None:
    if not GT_PATH.exists():
        raise SystemExit(f"Missing {GT_PATH}; run generate_adversarial_taxpayers.py first")
    cases = load_gt()
    regenerate_instances(cases)
    # Also refresh SampleTaxpayer from baseline fields
    subprocess.run([
        PY, str(ROOT / "scripts/generate_taxpayer_lean.py"),
        "--input", str(ROOT / "data/tax/taxpayer_fields.json"),
        "--instance-name", "sample_taxpayer",
        "--out", str(LEAN_DIR / "instances/SampleTaxpayer.lean"),
    ], check=True, cwd=str(ROOT))
    write_probe(cases)
    write_mirror_results(cases)


if __name__ == "__main__":
    main()
