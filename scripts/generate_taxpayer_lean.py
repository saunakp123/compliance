#!/usr/bin/env python3
"""
generate_taxpayer_lean.py
=========================
Generates a Lean 4 Taxpayer instance from a taxpayer_fields.json-shaped input.

Usage:
    py -3.12 scripts/generate_taxpayer_lean.py \
        --input data/tax/taxpayer_fields.json \
        --instance-name sample_taxpayer \
        --out Reglib_tax/Reglib/ITA/instances/SampleTaxpayer.lean

    # Adversarial instances:
    py -3.12 scripts/generate_taxpayer_lean.py \
        --input data/tax/adversarial/adv_01_ltcg_boundary.json \
        --instance-name adv_01_ltcg_boundary \
        --out Reglib_tax/Reglib/ITA/Adversarial_adv_01_ltcg_boundary.lean
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

# Fields present on Reglib.ITA.Taxpayer (Core.lean). Extra keys in the JSON
# (e.g. age_years) are skipped so generated instances always type-check.
TAXPAYER_FIELDS: list[str] = [
    "advance_tax_paid_amount",
    "advance_tax_threshold_pct",
    "assessed_tax_amount",
    "basic_exemption_limit",
    "basic_exemption_limit_senior",
    "basic_exemption_limit_super_senior",
    "days_in_india_fy",
    "dividend_income_amount",
    "dividend_tds_threshold",
    "health_insurance_premium_amount",
    "holding_period_months_equity",
    "interest_income_bank_amount",
    "interest_threshold_bank",
    "interest_threshold_senior_bank",
    "investment_80c_amount",
    "is_new_tax_regime",
    "is_pan_furnished",
    "is_resident",
    "is_return_filing_required",
    "is_senior_citizen",
    "is_stt_paid_at_acquisition",
    "is_stt_paid_on_transfer",
    "ltcg_exempt_limit",
    "ltcg_listed_equity_amount",
    "ltcg_tax_rate_pct_x10",
    "max_80c_deduction",
    "max_80d_deduction_self",
    "max_80d_deduction_senior",
    "max_rebate_87a",
    "max_rebate_87a_new",
    "rebate_87a_new_threshold",
    "rebate_87a_threshold",
    "stcg_listed_equity_amount",
    "stcg_tax_rate_pct",
    "tds_rate_194_dividend_pct",
    "tds_rate_194a_pct",
    "tds_rate_no_pan_pct",
    "total_income_amount",
]


def python_to_lean(value) -> str:
    """Convert a Python value to a Lean 4 literal."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return str(int(value))
    if isinstance(value, str):
        return f'"{value}"'
    return str(value)


def _repo_relative_comment(out_path: Path) -> str:
    """Prefer a repo-relative path in the Lean header (no machine-local abs paths)."""
    repo_root = Path(__file__).resolve().parents[1]
    try:
        return out_path.resolve().relative_to(repo_root).as_posix()
    except ValueError:
        return out_path.name


def generate_taxpayer_lean(fields: dict, instance_name: str, out_path: Path) -> str:
    lines = [
        f"-- {_repo_relative_comment(out_path)}",
        "-- Auto-generated by generate_taxpayer_lean.py -- DO NOT EDIT MANUALLY",
        "",
        "import Reglib.ITA.definitions.Core",
        "",
        "namespace Reglib.ITA",
        "",
        f"/-- Concrete Taxpayer instance `{instance_name}` for formal compliance checks. -/",
        f"def {instance_name} : Taxpayer := {{",
    ]
    for field in TAXPAYER_FIELDS:
        if field not in fields:
            continue
        lean_val = python_to_lean(fields[field])
        lines.append(f"  {field} := {lean_val},")
    lines.append("}")
    lines.append("")
    lines.append("end Reglib.ITA")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--input", "--fields",
        dest="fields",
        required=True,
        type=Path,
        help="Path to taxpayer_fields.json-shaped JSON",
    )
    parser.add_argument(
        "--out",
        required=True,
        type=Path,
        help="Output .lean path",
    )
    parser.add_argument(
        "--instance-name",
        default="sample_taxpayer",
        help="Lean def name for the Taxpayer instance",
    )
    args = parser.parse_args()

    with open(args.fields, encoding="utf-8") as f:
        fields = json.load(f)

    content = generate_taxpayer_lean(fields, args.instance_name, args.out)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(content, encoding="utf-8")
    print(f"[generate_taxpayer_lean] Written: {args.out}  (instance={args.instance_name})")


if __name__ == "__main__":
    main()
